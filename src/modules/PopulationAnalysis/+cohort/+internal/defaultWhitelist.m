function whitelist = defaultWhitelist()
    %DEFAULTWHITELIST Curated fingerprint metric whitelist (include/exclude substrings).
    %
    %   whitelist = cohort.internal.defaultWhitelist()
    %
    %   A metric column (as named by the cohort metrics functions) is included
    %   in the fingerprint when its name contains at least one Include
    %   substring (case-insensitive) and no Exclude substring. Substrings are
    %   matched with surrounding spaces where word boundaries matter (e.g.,
    %   ' Min ' does not match 'Minimum').
    %
    %   Family holds one label per Include substring (same order): the metric
    %   family of a name matched by that pattern. The FIRST matching Include
    %   pattern determines the family, so order-specific patterns must come
    %   first (e.g. 'Inactive Total Mean' before 'Last-First'). Several
    %   patterns may share one family label (the two Midline Crossings
    %   patterns). Used by cohort.internal.metricFamily as the single source
    %   of truth for family grouping in fingerprint figures.
    %
    %   The default covers the five behavioral families:
    %       Activity:      distance, speed mean, inactivity totals
    %       Exploration:   tortuosity, occupancy entropy
    %       Anxiety-like:  percent time near midline, midline crossings
    %       Valence:       preference index, percent time on stim side
    %       Dynamics:      last-first bout deltas, speed slope
    %
    %   Excluded: per-animal Min/Max/Std stats (tracking-artifact sensitive),
    %   first/last bout means (kept only as last-first deltas), post-stimulus
    %   columns, and head-derived metrics.

    arguments
    end

    whitelist = struct();
    whitelist.Include = { ...
        'Distance During', ...
        'Speed Mean During', ...
        'Inactive Total Mean', ...
        'Inactive Continuous Mean', ...
        'Tortuosity During', ...
        'Occupancy Entropy During', ...
        'Percent Time Near Midline During', ...
        'Speed Slope During', ...
        'Midline Crossings Into', ...
        'Midline Crossings During', ...
        'Preference Index During', ...
        'Percent Time on ', ...
        'Last-First' ...
        };
    whitelist.Family = { ...
        'Distance', ...
        'Speed Mean', ...
        'Inactive Total Mean', ...
        'Inactive Continuous Mean', ...
        'Tortuosity', ...
        'Occupancy Entropy', ...
        'Percent Time Near Midline', ...
        'Speed Slope', ...
        'Midline Crossings', ...
        'Midline Crossings', ...
        'Preference Index', ...
        'Percent Time on Side', ...
        'Last-First' ...
        };
    whitelist.Exclude = { ...
        ' Min ', ...
        ' Max ', ...
        ' Std ', ...
        'During First', ...
        'During Last', ...
        'During Post-Stimulus', ...
        'Head ' ...
        };
end
