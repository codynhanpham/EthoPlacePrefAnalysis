classdef testMetricFamily < matlab.unittest.TestCase
    methods (Test)
        function whitelistCarriesOneFamilyPerInclude(testCase)
            wl = cohort.internal.defaultWhitelist();
            testCase.verifyEqual(numel(wl.Family), numel(wl.Include));
            testCase.verifyTrue(all(strlength(string(wl.Family)) > 0));
        end

        function knownMetricsMapToFamilies(testCase)
            names = [ ...
                "Distance During Stimulus (cm)"; ...
                "Average Distance During Tone A (cm/s)"; ...
                "Distance During Pre-Stimulus (cm)"; ...
                "Speed Mean During Stimulus (cm/s)"; ...
                "Speed Slope During Pre-Stimulus (cm/s^2)"; ...
                "Inactive Total Mean During Stimulus (s)"; ...
                "Inactive Continuous Mean During Tone A (s)"; ...
                "Inactive Total Mean Last-First During Tone A Bouts (s)"; ...
                "Tortuosity During Stimulus (path/net)"; ...
                "Occupancy Entropy During Tone A (bits)"; ...
                "Percent Time Near Midline During Stimulus (%)"; ...
                "Midline Crossings During Stimulus (count)"; ...
                "Midline Crossings Into Tone A During Stimulus (count)"; ...
                "Midline Crossings Into Tone A Last-First Across Bouts (count)"; ...
                "Preference Index During Stimulus"; ...
                "Percent Time on Tone A Side During Stimulus (%)"; ...
                "Average Distance Last-First During Tone A Bouts (cm/s)"; ...
                "Speed Min During Stimulus (cm/s)"; ...
                "Head Speed Mean During Stimulus (cm/s)"];
            expected = ["Distance"; "Distance"; "Distance"; ...
                "Speed Mean"; "Speed Slope"; ...
                "Inactive Total Mean"; "Inactive Continuous Mean"; "Inactive Total Mean"; ...
                "Tortuosity"; "Occupancy Entropy"; "Percent Time Near Midline"; ...
                "Midline Crossings"; "Midline Crossings"; "Midline Crossings"; ...
                "Preference Index"; "Percent Time on Side"; ...
                "Last-First"; "Other"; "Other"];

            [fam, pattern] = cohort.internal.metricFamily(names);
            testCase.verifyEqual(string(fam), expected);

            % Matched pattern is the first (most specific) include hit.
            lastFirstInactive = names == "Inactive Total Mean Last-First During Tone A Bouts (s)";
            testCase.verifyEqual(pattern(lastFirstInactive), "Inactive Total Mean");

            % Excluded / unmatched names carry no pattern.
            other = expected == "Other";
            testCase.verifyTrue(all(strlength(pattern(other)) == 0));
        end

        function acceptsCharCellAndStringInputs(testCase)
            f1 = cohort.internal.metricFamily('Distance During Stimulus (cm)');
            f2 = cohort.internal.metricFamily("Distance During Stimulus (cm)");
            f3 = cohort.internal.metricFamily({'Distance During Stimulus (cm)'});
            testCase.verifyEqual(string(f1), "Distance");
            testCase.verifyEqual(string(f2), "Distance");
            testCase.verifyEqual(string(f3), "Distance");
            testCase.verifyEqual(numel(cohort.internal.metricFamily(["Tortuosity During Stimulus (x)"; "Distance During Stimulus (cm)"])), 2);
        end

        function mismatchedWhitelistErrors(testCase)
            wl = cohort.internal.defaultWhitelist();
            wl.Family(1) = [];
            testCase.verifyError(@() cohort.internal.metricFamily("Distance During Stimulus (cm)", Whitelist=wl), ...
                'cohort:internal:metricFamily:BadWhitelist');
        end
    end
end
