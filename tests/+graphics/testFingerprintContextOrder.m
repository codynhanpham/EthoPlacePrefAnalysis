classdef testFingerprintContextOrder < matlab.unittest.TestCase
    methods (Test)
        function ordersByTierThenFamilyThenMetric(testCase)
            colLabels = table( ...
                categorical(["stim_all"; "baseline"; "stim_all"; "baseline"]), ...
                categorical([2; 1; 2; 1]), ...
                ["ALL"; "ALL"; "ALL"; "ALL"], ...
                ["Distance During Stimulus (cm)"; "Distance During Pre-Stimulus (cm)"; ...
                "Tortuosity During Stimulus (path/net)"; "Speed Mean During Pre-Stimulus (cm/s)"], ...
                'VariableNames', {'Tier', 'Protocol', 'Stimulus', 'Metric'});
            fp = struct('colLabels', colLabels);

            order = graphics.fingerprintContextOrder(fp);

            % baseline before stim_all; families alphabetical inside each
            % tier block: baseline -> Distance (2), Speed Mean (4);
            % stim_all -> Distance (1), Tortuosity (3).
            testCase.verifyEqual(order, [2; 4; 1; 3]);
        end

        function protocolAndStimulusSortAboveFamily(testCase)
            colLabels = table( ...
                categorical(["stim_all"; "stim_all"; "stim_all"; "stim_all"]), ...
                categorical([2; 2; 1; 1]), ...
                ["Tone B"; "Tone B"; "Tone A"; "Tone A"], ...
                ["Tortuosity During Tone B (path/net)"; "Distance During Tone B (cm)"; ...
                "Distance During Tone A (cm)"; "Tortuosity During Tone A (path/net)"], ...
                'VariableNames', {'Tier', 'Protocol', 'Stimulus', 'Metric'});
            fp = struct('colLabels', colLabels);

            order = graphics.fingerprintContextOrder(fp);

            % protocol 1 before 2; within protocol, stimulus A before B;
            % family only breaks ties inside the same stimulus block.
            testCase.verifyEqual(order, [3; 4; 2; 1]);
        end
    end
end
