classdef testHeadReactionTimeByBout < matlab.unittest.TestCase
    methods (Test)
        function angularVelocityModeComputesLatency(testCase)
            % Constant clockwise rotation: bearing increases 90 deg per 0.1 s
            % frame -> 900 deg/s everywhere, so the peak latency is the first
            % post-onset sample (0 s).
            standardizedTable = makeRotationTable([0; 90; 180; -90; 0]);
            f = graphics.headReactionTimeByBout(standardizedTable, ...
                'ReactionMetric', 'angularVelocity', 'ResponseWindow', [-0.1, 0.4], ...
                'PostOnsetWindow', [0, 0.4], 'BaselineWindow', [-0.1, 0]);
            testCase.verifyTrue(isgraphics(f, 'figure'));
            close(f);
        end

        function mixedModeRunsAndPicksLowestLatency(testCase)
            % Two replicates: replicate 1 has an early velocity peak, replicate 2
            % an early acceleration peak; mixed mode must run and produce a figure.
            standardizedTable = makeMixedTable();
            f = graphics.headReactionTimeByBout(standardizedTable, ...
                'ReactionMetric', 'mixed', 'ResponseWindow', [-0.1, 0.4], ...
                'PostOnsetWindow', [0, 0.4], 'BaselineWindow', [-0.1, 0], ...
                'ResponseSDThreshold', NaN);
            testCase.verifyTrue(isgraphics(f, 'figure'));
            close(f);
        end

        function missingNoseFallsBackGracefully(testCase)
            % Without nose columns, angularVelocity mode yields empty boxes but
            % must not error; mixed mode falls back to the other two metrics.
            standardizedTable = makeRotationTable([0; 90; 180; -90; 0]);
            standardizedTable.bodyparts = ...
                standardizedTable.bodyparts(:, setdiff( ...
                standardizedTable.bodyparts.Properties.VariableNames, ...
                {'X nose', 'Y nose'}, 'stable'));

            f = graphics.headReactionTimeByBout(standardizedTable, ...
                'ReactionMetric', 'angularVelocity', 'ResponseWindow', [-0.1, 0.4], ...
                'PostOnsetWindow', [0, 0.4], 'BaselineWindow', [-0.1, 0]);
            testCase.verifyTrue(isgraphics(f, 'figure'));
            close(f);

            f = graphics.headReactionTimeByBout(standardizedTable, ...
                'ReactionMetric', 'mixed', 'ResponseWindow', [-0.1, 0.4], ...
                'PostOnsetWindow', [0, 0.4], 'BaselineWindow', [-0.1, 0], ...
                'ResponseSDThreshold', NaN);
            testCase.verifyTrue(isgraphics(f, 'figure'));
            close(f);
        end

        function wrapTransitionYieldsPositiveAngularVelocity(testCase)
            % Bearing 359 -> 1 deg must give +2 deg/s, not -358. Verified via the
            % cohort metric on the same geometry (shared convention).
            bearingDegrees = [359; 1];
            standardizedTable = makeBearingFixture(bearingDegrees);
            result = cohort.metrics.headAngularVelocity(standardizedTable);
            testCase.verifyEqual(result.('Head Angular Velocity Mean During Stimulus (deg/s)'), 20, 'AbsTol', 1e-9);
        end
    end
end

function standardizedTable = makeRotationTable(bearingDegrees)
% One animal rotating with the given bearing per frame (image convention).
nRows = numel(bearingDegrees);
trialTime = (0:nRows-1)' / 10;
stimulusName = repmat("A", nRows, 1);
midX = zeros(nRows, 1);
midY = zeros(nRows, 1);
directionX = sind(bearingDegrees);
directionY = -cosd(bearingDegrees);
noseX = midX + directionX;
noseY = midY + directionY;
leftX = midX - 1;
leftY = midY;
rightX = midX + 1;
rightY = midY;

centerpointData = table(trialTime, stimulusName, ...
    midX, midY, zeros(nRows, 1), zeros(nRows, 1), ...
    'VariableNames', {'Trial time', 'Stimulus name', 'X center', ...
    'Y center', 'Distance from Midline', 'Arena Grid Score'});
bodyparts = table(trialTime, stimulusName, leftX, leftY, rightX, rightY, ...
    noseX, noseY, ...
    'VariableNames', {'Trial time', 'Stimulus name', ...
    'X Ear_left', 'Y Ear_left', 'X Ear_right', 'Y Ear_right', ...
    'X nose', 'Y nose'});

metadata = configureDictionary("string", "struct");
metadata("animal1") = struct('sex', 'F', 'strain', 'strain', 'genotype', 'genotype');

standardizedTable = struct(...
    'stimfileName', "stimulus.flac", ...
    'stimuliSorted', ["A"], ...
    'animalMetadata', metadata, ...
    'fps', 10, ...
    'px2cm', 0.5, ...
    'centerpointData', centerpointData, ...
    'bodyparts', bodyparts);
end

function standardizedTable = makeMixedTable()
% Two animals over one stimulus: replicate 1 moves fast early (velocity wins),
% replicate 2 turns fast early (angular velocity wins).
nRows = 5;
trialTime = (0:nRows-1)' / 10;
stimulusName = repmat("A", nRows, 1);
midX = zeros(nRows, 2);
midY = zeros(nRows, 2);
% Replicate 1: fast translation along +X (speed peaks at onset).
midX(:, 1) = [0; 1; 2; 3; 4];
midY(:, 1) = zeros(nRows, 1);
% Replicate 2: fast clockwise rotation (angular velocity peaks at onset).
bearing = [0; 90; 180; -90; 0];
directionX = sind(bearing);
directionY = -cosd(bearing);
noseX = midX + directionX;
noseY = midY + directionY;
leftX = midX - 1;
leftY = midY;
rightX = midX + 1;
rightY = midY;

centerpointData = table(trialTime, stimulusName, ...
    midX, midY, zeros(nRows, 2), zeros(nRows, 2), ...
    'VariableNames', {'Trial time', 'Stimulus name', 'X center', ...
    'Y center', 'Distance from Midline', 'Arena Grid Score'});
bodyparts = table(trialTime, stimulusName, leftX, leftY, rightX, rightY, ...
    noseX, noseY, ...
    'VariableNames', {'Trial time', 'Stimulus name', ...
    'X Ear_left', 'Y Ear_left', 'X Ear_right', 'Y Ear_right', ...
    'X nose', 'Y nose'});

metadata = configureDictionary("string", "struct");
metadata("animal1") = struct('sex', 'F', 'strain', 'strain', 'genotype', 'genotype');
metadata("animal2") = struct('sex', 'M', 'strain', 'strain', 'genotype', 'genotype');

standardizedTable = struct(...
    'stimfileName', "stimulus.flac", ...
    'stimuliSorted', ["A"], ...
    'animalMetadata', metadata, ...
    'fps', 10, ...
    'px2cm', 0.5, ...
    'centerpointData', centerpointData, ...
    'bodyparts', bodyparts);
end

